"""Rebuild the downloadable zip files from the folders in materials/.

Run this from the repository root whenever you change anything in materials/:

    python scripts/make_zips.py

It (re)creates:
    downloads/BBWDP_data.zip <- materials/starter/
    downloads/solution.zip   <- materials/solution/
    downloads/template.zip   <- materials/template/
    assets/solution-data.js  <- used by the "Check your work" tool
"""
import json
import os
import re
import zipfile
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MATERIALS = os.path.join(ROOT, "materials")
DOWNLOADS = os.path.join(ROOT, "downloads")
FIXED_DATE = (2024, 1, 1, 0, 0, 0)  # same timestamp every build -> no needless git changes


ZIP_NAMES = {"starter": "BBWDP_data", "solution": "solution", "template": "template"}


def zip_folder(name):
    src = os.path.join(MATERIALS, name)
    dest = os.path.join(DOWNLOADS, f"{ZIP_NAMES[name]}.zip")
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as zf:
        for folder, dirs, files in os.walk(src):
            dirs.sort()
            for fname in sorted(files):
                full = os.path.join(folder, fname)
                arc = os.path.relpath(full, src).replace(os.sep, "/")
                info = zipfile.ZipInfo(arc, FIXED_DATE)
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = 0o644 << 16
                with open(full, "rb") as f:
                    zf.writestr(info, f.read())
    print(f"wrote {os.path.relpath(dest, ROOT)}")


def write_checker_data():
    """Describe the solution so the 'Check your work' tool on the web page can
    compare a learner's folder with it. Files are matched by content (CRC32 +
    size), so the check still works after files have been renamed and moved."""
    sol_root = os.path.join(MATERIALS, "solution")
    project = sorted(d for d in os.listdir(sol_root) if os.path.isdir(os.path.join(sol_root, d)))[0]
    base = os.path.join(sol_root, project)
    # projectcode_description_vNN.ext
    pattern = re.compile(r"^([a-z0-9]+)_([a-z0-9-]+)_v(\d{2})\.([A-Za-z0-9]+)$")
    files, folders, code = [], set(), None
    for folder, dirs, names in os.walk(base):
        dirs.sort()
        rel_folder = os.path.relpath(folder, base).replace(os.sep, "/")
        if rel_folder != ".":
            folders.add(rel_folder)
        for n in sorted(names):
            with open(os.path.join(folder, n), "rb") as f:
                data = f.read()
            m = pattern.match(n)
            if m:
                code = m.group(1)
            files.append({
                "name": n,
                "folder": "" if rel_folder == "." else rel_folder,
                "crc": zlib.crc32(data) & 0xFFFFFFFF,
                "size": len(data),
                "version": m.group(3) if m else None,
            })
    # Names of the same files in the starter folder (matched by content), so the
    # checker can tell "not renamed yet" apart from "renamed, but not to the convention".
    starter_names = {}
    st_root = os.path.join(MATERIALS, "starter")
    for folder, dirs, names in os.walk(st_root):
        for n in names:
            with open(os.path.join(folder, n), "rb") as f:
                data = f.read()
            starter_names[(zlib.crc32(data) & 0xFFFFFFFF, len(data))] = n
    for f in files:
        f["starterName"] = starter_names.get((f["crc"], f["size"]))
    out = {"project": project, "code": code, "folders": sorted(folders), "files": files,
           "minRenamed": 3}
    dest = os.path.join(ROOT, "assets", "solution-data.js")
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by scripts/make_zips.py - do not edit by hand.\n")
        f.write("window.SOLUTION = " + json.dumps(out, indent=2) + ";\n")
    print(f"wrote {os.path.relpath(dest, ROOT)}")


if __name__ == "__main__":
    os.makedirs(DOWNLOADS, exist_ok=True)
    for name in ("starter", "solution", "template"):
        zip_folder(name)
    write_checker_data()
